//! Dart's `Uri.parse` and `Uri.decodeComponent`, as far as the share-link
//! parsers use them (user info, host, port, query parameters, fragment).
//!
//! Ported from `dart:core/uri.dart` (Dart 3.13): the same scanner state table
//! splits the string, then each part is validated and normalized the way
//! `_Uri.notSimple` does (host lower-cased, characters outside a part's set
//! percent-encoded, a stray `%` written as `%25`, malformed parts rejected).
//! Dart takes a fast path for URIs already in that normal form; it yields
//! the same parts, so only the general path is ported. The path is never
//! read and is not computed.

use std::collections::HashMap;
use std::net::Ipv6Addr;

use crate::dart::{int_try_parse, utf8_decode};

/// A string Dart's `Uri.parse` rejects (it throws `FormatException`).
#[derive(Debug)]
pub(crate) struct BadUri;

/// Why `Uri.decodeComponent` (or a query parameter) failed to decode.
#[derive(Debug, PartialEq, Eq)]
pub(crate) enum DecodeError {
    /// Dart's `ArgumentError`: a non-ASCII character or a broken `%` escape.
    Argument,
    /// Dart's `FormatException`: the escapes are not valid UTF-8.
    Format,
}

/// The parts of a parsed URI the parsers read.
pub(crate) struct Uri {
    user_info: String,
    /// Normalized; IPv6 addresses keep their brackets here.
    host: Option<String>,
    port: Option<i64>,
    default_port: i64,
    query: Option<String>,
    fragment: Option<String>,
}

impl Uri {
    /// `Uri.parse(s)`.
    pub(crate) fn parse(s: &str) -> Result<Self, BadUri> {
        let b = s.as_bytes();
        let end = isize::try_from(b.len()).map_err(|_| BadUri)?;
        let mut idx: [isize; 8] = [0, -1, -1, 0, 0, end, end, -1];
        let state = scan(b, 0, end, URI_START, &mut idx);
        if state >= NON_SIMPLE_END_STATES {
            idx[NOT_SIMPLE] = end;
        }
        let scheme_end = idx[SCHEME_END];
        if scheme_end >= 0 {
            scan(b, 0, scheme_end, SCHEME_START, &mut idx);
        }
        let host_start = idx[HOST_START] + 1;
        let mut port_start = idx[PORT_START];
        let mut path_start = idx[PATH_START];
        let mut query_start = idx[QUERY_START];
        let fragment_start = idx[FRAGMENT_START];
        if fragment_start < query_start {
            query_start = fragment_start;
        }
        if path_start < host_start {
            path_start = query_start;
        } else if path_start <= scheme_end {
            path_start = scheme_end + 1;
        }
        if port_start < host_start {
            port_start = path_start;
        }

        let part = |a: isize, z: isize| -> Result<&str, BadUri> {
            let a = usize::try_from(a).map_err(|_| BadUri)?;
            let z = usize::try_from(z).map_err(|_| BadUri)?;
            s.get(a..z).ok_or(BadUri)
        };
        let scheme = match scheme_end {
            0 => return Err(BadUri), // "Invalid empty scheme"
            e if e > 0 => make_scheme(part(0, e)?)?,
            _ => String::new(),
        };
        let default_port = match scheme.as_str() {
            "http" => 80,
            "https" => 443,
            _ => 0,
        };
        let mut user_info = String::new();
        let mut host = None;
        let mut port = None;
        if host_start > 0 {
            let user_info_start = scheme_end + 3;
            if user_info_start < host_start {
                user_info =
                    normalize(s, user_info_start, host_start - 1, is_user_info_char, false)?;
            }
            host = Some(make_host(s, host_start, port_start)?);
            if port_start + 1 < path_start {
                let p = int_try_parse(part(port_start + 1, path_start)?).ok_or(BadUri)?;
                port = (p != default_port).then_some(p);
            }
        }
        let query = if query_start < fragment_start {
            Some(normalize(
                s,
                query_start + 1,
                fragment_start,
                is_query_char,
                true,
            )?)
        } else {
            None
        };
        let fragment = if fragment_start < end {
            Some(normalize(s, fragment_start + 1, end, is_query_char, true)?)
        } else {
            None
        };
        Ok(Self {
            user_info,
            host,
            port,
            default_port,
            query,
            fragment,
        })
    }

    /// `uri.userInfo` (normalized, still percent-encoded).
    pub(crate) fn user_info(&self) -> &str {
        &self.user_info
    }

    /// `uri.host`: IPv6 without its brackets (an IPvFuture keeps them).
    pub(crate) fn host(&self) -> &str {
        let h = self.host.as_deref().unwrap_or_default();
        if h.starts_with('[') && !h[1..].starts_with('v') {
            &h[1..h.len() - 1]
        } else {
            h
        }
    }

    /// `uri.port`: the scheme's default (0 for share links) when absent.
    pub(crate) fn port(&self) -> i64 {
        self.port.unwrap_or(self.default_port)
    }

    /// `uri.hasPort`: an explicit port other than the scheme's default.
    pub(crate) fn has_port(&self) -> bool {
        self.port.is_some()
    }

    /// `uri.fragment` (normalized, still percent-encoded).
    pub(crate) fn fragment(&self) -> &str {
        self.fragment.as_deref().unwrap_or_default()
    }

    /// `uri.queryParameters`: `+` is a space; for a repeated key the last
    /// value wins; `=value` without a key is dropped.
    pub(crate) fn query_parameters(&self) -> Result<HashMap<String, String>, DecodeError> {
        let mut map = HashMap::new();
        for element in self.query.as_deref().unwrap_or_default().split('&') {
            match element.find('=') {
                None if !element.is_empty() => {
                    map.insert(uri_decode(element, true)?, String::new());
                }
                Some(i) if i != 0 => {
                    map.insert(
                        uri_decode(&element[..i], true)?,
                        uri_decode(&element[i + 1..], true)?,
                    );
                }
                _ => {}
            }
        }
        Ok(map)
    }
}

/// `Uri.decodeComponent(s)`.
pub(crate) fn decode_component(s: &str) -> Result<String, DecodeError> {
    uri_decode(s, false)
}

/// Dart's `_Uri._uriDecode` with UTF-8.
fn uri_decode(text: &str, plus_to_space: bool) -> Result<String, DecodeError> {
    let b = text.as_bytes();
    let simple = !b
        .iter()
        .any(|&c| c > 127 || c == b'%' || (plus_to_space && c == b'+'));
    if simple {
        return Ok(text.to_owned());
    }
    let mut bytes = Vec::with_capacity(b.len());
    let mut i = 0;
    while i < b.len() {
        let c = b[i];
        if c > 127 {
            return Err(DecodeError::Argument);
        }
        if c == b'%' {
            if i + 3 > b.len() {
                return Err(DecodeError::Argument);
            }
            let hi = hex_value(b[i + 1]).ok_or(DecodeError::Argument)?;
            let lo = hex_value(b[i + 2]).ok_or(DecodeError::Argument)?;
            bytes.push(hi * 16 + lo);
            i += 3;
            continue;
        }
        bytes.push(if plus_to_space && c == b'+' { b' ' } else { c });
        i += 1;
    }
    utf8_decode(bytes).ok_or(DecodeError::Format)
}

fn hex_value(c: u8) -> Option<u8> {
    char::from(c)
        .to_digit(16)
        .and_then(|d| u8::try_from(d).ok())
}

// ---------------------------------------------------------------- parts

fn is_unreserved(c: u8) -> bool {
    c.is_ascii_alphanumeric() || matches!(c, b'-' | b'.' | b'_' | b'~')
}

fn is_sub_delim(c: u8) -> bool {
    matches!(
        c,
        b'!' | b'$' | b'&' | b'\'' | b'(' | b')' | b'*' | b'+' | b',' | b';' | b'='
    )
}

fn is_user_info_char(c: u8) -> bool {
    is_unreserved(c) || is_sub_delim(c) || c == b':'
}

fn is_query_char(c: u8) -> bool {
    is_unreserved(c) || is_sub_delim(c) || matches!(c, b':' | b'@' | b'/' | b'?')
}

fn is_gen_delim(c: u8) -> bool {
    matches!(c, b':' | b'/' | b'?' | b'#' | b'[' | b']' | b'@')
}

/// What `_normalizeEscape` makes of the `%` at `i`.
enum Escape {
    /// Already normal: keep the three characters.
    Keep,
    /// Not followed by two hex digits: the `%` becomes `%25`.
    Invalid,
    /// An unreserved character, or the escape with upper-case digits.
    Replace(String),
}

fn normalize_escape(s: &[u8], i: usize, lower_case: bool) -> Escape {
    let (Some(&d1), Some(&d2)) = (s.get(i + 1), s.get(i + 2)) else {
        return Escape::Invalid;
    };
    let (Some(h), Some(l)) = (hex_value(d1), hex_value(d2)) else {
        return Escape::Invalid;
    };
    let value = h * 16 + l;
    if is_unreserved(value) {
        let c = if lower_case {
            value.to_ascii_lowercase()
        } else {
            value
        };
        return Escape::Replace(char::from(c).to_string());
    }
    if d1.is_ascii_lowercase() || d2.is_ascii_lowercase() {
        return Escape::Replace(
            format!("%{}{}", char::from(d1), char::from(d2)).to_ascii_uppercase(),
        );
    }
    Escape::Keep
}

/// Percent-encodes `c` as UTF-8 with upper-case hex digits.
fn push_escaped(out: &mut String, c: char) {
    const HEX: &[u8; 16] = b"0123456789ABCDEF";
    let mut buf = [0u8; 4];
    for byte in c.encode_utf8(&mut buf).bytes() {
        out.push('%');
        out.push(char::from(HEX[usize::from(byte >> 4)]));
        out.push(char::from(HEX[usize::from(byte & 0xF)]));
    }
}

/// `_normalize`: keeps `allowed` characters and good escapes, encodes the
/// rest; a general delimiter is an error unless `escape_delimiters`.
fn normalize(
    s: &str,
    start: isize,
    end: isize,
    allowed: fn(u8) -> bool,
    escape_delimiters: bool,
) -> Result<String, BadUri> {
    let (start, end) = range(start, end)?;
    let b = s.as_bytes();
    let mut out = String::with_capacity(end - start);
    let mut i = start;
    while i < end {
        let c = b[i];
        if c.is_ascii() && allowed(c) {
            out.push(char::from(c));
            i += 1;
        } else if c == b'%' {
            match normalize_escape(b, i, false) {
                Escape::Keep => {
                    out.push_str(&s[i..i + 3]);
                    i += 3;
                }
                Escape::Invalid => {
                    out.push_str("%25");
                    i += 1;
                }
                Escape::Replace(r) => {
                    out.push_str(&r);
                    i += 3;
                }
            }
        } else if !escape_delimiters && is_gen_delim(c) {
            return Err(BadUri);
        } else {
            let ch = s[i..].chars().next().ok_or(BadUri)?;
            push_escaped(&mut out, ch);
            i += ch.len_utf8();
        }
    }
    Ok(out)
}

/// `_normalizeRegName`: as [`normalize`] for a host name, lower-cased.
fn normalize_reg_name(s: &str, start: usize, end: usize) -> Result<String, BadUri> {
    let b = s.as_bytes();
    let mut out = String::with_capacity(end - start);
    let mut i = start;
    while i < end {
        let c = b[i];
        if c == b'%' {
            match normalize_escape(b, i, true) {
                Escape::Keep => {
                    out.push_str(&s[i..i + 3]);
                    i += 3;
                }
                Escape::Invalid => {
                    out.push_str("%25");
                    i += 1;
                }
                Escape::Replace(r) => {
                    out.push_str(&r);
                    i += 3;
                }
            }
        } else if c.is_ascii() && (is_unreserved(c) || is_sub_delim(c)) {
            out.push(char::from(c.to_ascii_lowercase()));
            i += 1;
        } else if is_gen_delim(c) {
            return Err(BadUri);
        } else {
            let ch = s[i..].chars().next().ok_or(BadUri)?;
            push_escaped(&mut out, ch);
            i += ch.len_utf8();
        }
    }
    Ok(out)
}

/// `_normalizeZoneID` with the `%25` prefix.
fn normalize_zone_id(s: &str, start: usize, end: usize) -> Result<String, BadUri> {
    let b = s.as_bytes();
    let mut out = String::from("%25");
    let mut i = start;
    while i < end {
        let c = b[i];
        if c == b'%' {
            match normalize_escape(b, i, true) {
                Escape::Keep => out.push_str(&s[i..i + 3]),
                Escape::Invalid => return Err(BadUri),
                Escape::Replace(r) => out.push_str(&r),
            }
            i += 3;
        } else if is_unreserved(c) {
            out.push(char::from(c));
            i += 1;
        } else {
            let ch = s[i..].chars().next().ok_or(BadUri)?;
            push_escaped(&mut out, ch);
            i += ch.len_utf8();
        }
    }
    Ok(out)
}

/// `_makeScheme`: letters, digits, `+-.`, starting with a letter; lower-cased.
fn make_scheme(scheme: &str) -> Result<String, BadUri> {
    let b = scheme.as_bytes();
    if !b[0].is_ascii_alphabetic()
        || !b
            .iter()
            .all(|&c| c.is_ascii_alphanumeric() || matches!(c, b'+' | b'-' | b'.'))
    {
        return Err(BadUri);
    }
    Ok(scheme.to_ascii_lowercase())
}

/// `_makeHost(host, start, end, strictIPv6: false)`.
fn make_host(s: &str, start: isize, end: isize) -> Result<String, BadUri> {
    let (start, end) = range(start, end)?;
    if start == end {
        return Ok(String::new());
    }
    let b = s.as_bytes();
    // The zone (after `%`, `%25` dropped) of the address in start..end.
    let zone = |from: usize, to: usize| -> Result<(usize, String), BadUri> {
        let Some(pct) = s[from..to].find('%') else {
            return Ok((to, String::new()));
        };
        let index = from + pct;
        let zone_start = if s[index + 1..].starts_with("25") {
            index + 3
        } else {
            index + 1
        };
        Ok((index, normalize_zone_id(s, zone_start.min(to), to)?))
    };
    if b[start] == b'[' {
        if b[end - 1] != b']' {
            return Err(BadUri);
        }
        let (index, zone_id) = if b[start + 1] == b'v' {
            (end - 1, String::new())
        } else {
            zone(start + 1, end - 1)?
        };
        let is_ipv6 = validate_ip_literal(&s[start + 1..index])?;
        let chars = &s[start + 1..index];
        let chars = if is_ipv6 {
            chars.to_ascii_lowercase()
        } else {
            chars.to_owned()
        };
        return Ok(format!("[{chars}{zone_id}]"));
    }
    if s[start..end].contains(':') {
        // An IPv6 address without brackets (case kept).
        let (index, zone_id) = zone(start, end)?;
        s[start..index].parse::<Ipv6Addr>().map_err(|_| BadUri)?;
        return Ok(format!("[{}{zone_id}]", &s[start..index]));
    }
    normalize_reg_name(s, start, end)
}

/// `_validateIPvAddress`: true for IPv6, false for a valid IPvFuture.
fn validate_ip_literal(a: &str) -> Result<bool, BadUri> {
    let Some(rest) = a.strip_prefix('v') else {
        a.parse::<Ipv6Addr>().map_err(|_| BadUri)?;
        return Ok(true);
    };
    // IPvFuture: v<hex>.<unreserved / sub-delims / ":">+
    let (version, address) = rest.split_once('.').ok_or(BadUri)?;
    let ok = !version.is_empty()
        && version.bytes().all(|c| c.is_ascii_hexdigit())
        && !address.is_empty()
        && address.bytes().all(is_user_info_char);
    if ok {
        Ok(false)
    } else {
        Err(BadUri)
    }
}

fn range(start: isize, end: isize) -> Result<(usize, usize), BadUri> {
    let start = usize::try_from(start).map_err(|_| BadUri)?;
    let end = usize::try_from(end).map_err(|_| BadUri)?;
    if start > end {
        return Err(BadUri);
    }
    Ok((start, end))
}

