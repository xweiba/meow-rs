/// Dart's `_scan`: runs the state machine over `s[start..end]`, recording
/// positions in `idx`. Bytes rather than UTF-16 units: every non-ASCII unit
/// takes the same transition, which is idempotent in every state, so a
/// multi-byte character scans like a single unit.
fn scan(s: &[u8], start: isize, end: isize, mut state: usize, idx: &mut [isize; 8]) -> usize {
    for i in start..end {
        let Ok(at) = usize::try_from(i) else {
            continue;
        };
        let mut c = usize::from(s[at] ^ 0x60);
        if c > 95 {
            c = 0x7F ^ 0x60;
        }
        let t = SCANNER_TABLE[state * 96 + c];
        state = usize::from(t & 31);
        idx[usize::from(t >> 5)] = i;
    }
    state
}

