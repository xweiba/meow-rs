//! Read-only compatibility with the former Linux resolver rewrite.
//!
//! TUN DNS capture uses temporary packet interception/routes. No platform
//! rewrites resolver settings, resets adapters to DHCP, or guesses which
//! configured DNS values belong to an older core. An old Linux marker may
//! still have a precise sidecar; read it without restoring or deleting it.

#[cfg(target_os = "linux")]
pub(super) fn original_resolv_conf() -> Option<String> {
    let current = std::fs::read_to_string("/etc/resolv.conf").ok()?;
    original(&current, || {
        std::fs::read_to_string("/etc/resolv.conf.meow-backup").ok()
    })
}

#[cfg(any(target_os = "linux", test))]
fn original(current: &str, backup: impl FnOnce() -> Option<String>) -> Option<String> {
    if current.starts_with("# Generated by meow-rs TUN dns-guard") {
        // Missing recovery data is unknown. Never invent public resolvers
        // or strip a user's static loopback/fake-range DNS values.
        backup()
    } else {
        Some(current.to_owned())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn configured_dns_is_returned_verbatim_without_address_heuristics() {
        let configured = "# custom DNS\nsearch corp.example\nnameserver 127.0.0.1\n\
                          nameserver ::1\nnameserver 198.18.0.1\n";
        assert_eq!(
            original(configured, || panic!("not an owned rewrite")),
            Some(configured.into())
        );
    }

    #[test]
    fn legacy_marker_requires_exact_backup_and_never_guesses_a_replacement() {
        let legacy = "# Generated by meow-rs TUN dns-guard\nnameserver 198.18.0.1\n";
        let saved = "nameserver 192.0.2.53\nsearch corp.example\n";
        assert_eq!(original(legacy, || Some(saved.into())), Some(saved.into()));
        assert_eq!(original(legacy, || None), None);
    }
}
